package br.com.fiap.nextbus.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(0)
public class IdempotenciaSchema implements CommandLineRunner {

    private static final String SQL = """
            BEGIN
                EXECUTE IMMEDIATE 'CREATE TABLE IDEMPOTENCIA (
                    id_idempotencia NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_usuario NUMBER NOT NULL,
                    chave VARCHAR2(80 CHAR) NOT NULL,
                    hash_corpo VARCHAR2(128 CHAR) NOT NULL,
                    id_rotina NUMBER NOT NULL,
                    CONSTRAINT IDEMPOTENCIA_CHAVE_UK UNIQUE (id_usuario, chave)
                )';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -955 THEN
                        RAISE;
                    END IF;
            END;
            """;

    private final JdbcTemplate jdbcTemplate;

    public IdempotenciaSchema(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        try {
            jdbcTemplate.execute(SQL);
        } catch (DataAccessException ex) {
            throw new IllegalStateException(
                    "Não foi possível criar a tabela IDEMPOTENCIA. Rode db/003-idempotencia.sql no SQL Developer, com F5, na conexão FIAP.",
                    ex);
        }
    }
}
