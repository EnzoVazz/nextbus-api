    private void aviso(int id, int rotina, String data, String letreiro, String ponto,
                       String veiculo, String minutos, String gps, String texto, String status) {
        garantir("""
                INSERT INTO AVISO (
                    id_aviso, id_rotina, data_aviso, letreiro, nome_ponto,
                    identificador_veiculo, minutos, idade_gps_segundos, texto, status
                )
                SELECT %d, %d, DATE '%s', '%s', '%s', %s, %s, %s, '%s', '%s' FROM DUAL
                WHERE NOT EXISTS (SELECT 1 FROM AVISO WHERE id_aviso = %d)
                """.formatted(id, rotina, data, letreiro, ponto, sqlTexto(veiculo), numero(minutos), numero(gps), texto, status, id));
    }

    private String sqlTexto(String valor) {
        return valor == null ? "NULL" : "'" + valor + "'";
    }

    private String numero(String valor) {
        return valor == null ? "NULL" : valor;
    }

    private void garantir(String sql) {
        try {
            jdbcTemplate.execute(sql);
        } catch (DataAccessException ex) {
            int codigo = codigoOracle(ex);
            if (JA_EXISTE.contains(Math.abs(codigo))) {
                return;
            }
            throw new IllegalStateException("Não foi possível preparar as tabelas do NextBus.", ex);
        }
    }

    private int codigoOracle(Throwable ex) {
        Throwable atual = ex;
        while (atual != null) {
            if (atual instanceof SQLException sql) {
                if (sql.getErrorCode() != 0) {
                    return sql.getErrorCode();
                }
                SQLException proxima = sql.getNextException();
                if (proxima != null && proxima.getErrorCode() != 0) {
                    return proxima.getErrorCode();
                }
            }
            atual = atual.getCause();
        }
        return 0;
    }
