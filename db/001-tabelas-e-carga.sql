CREATE TABLE USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    nome       VARCHAR2(120) NOT NULL,
    email      VARCHAR2(160) NOT NULL,
    papel      VARCHAR2(20)  NOT NULL
);

ALTER TABLE USUARIO ADD CONSTRAINT USUARIO_PK PRIMARY KEY (id_usuario);
ALTER TABLE USUARIO ADD CONSTRAINT USUARIO_EMAIL_UK UNIQUE (email);
ALTER TABLE USUARIO ADD CONSTRAINT USUARIO_PAPEL_CK CHECK (papel IN ('CIDADAO', 'GESTOR'));

CREATE TABLE ROTINA (
    id_rotina        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    id_usuario       NUMBER        NOT NULL,
    codigo_linha     VARCHAR2(20)  NOT NULL,
    letreiro         VARCHAR2(20)  NOT NULL,
    sentido          NUMBER(1)     NOT NULL,
    codigo_parada    VARCHAR2(20)  NOT NULL,
    nome_parada      VARCHAR2(160) NOT NULL,
    dias_semana      VARCHAR2(20)  NOT NULL,
    horario_embarque CHAR(5)       NOT NULL,
    ativa            CHAR(1)       DEFAULT 'S' NOT NULL
);

ALTER TABLE ROTINA ADD CONSTRAINT ROTINA_PK PRIMARY KEY (id_rotina);
ALTER TABLE ROTINA ADD CONSTRAINT ROTINA_SENTIDO_CK CHECK (sentido IN (1, 2));
ALTER TABLE ROTINA ADD CONSTRAINT ROTINA_ATIVA_CK CHECK (ativa IN ('S', 'N'));
ALTER TABLE ROTINA ADD CONSTRAINT ROTINA_HORARIO_CK
    CHECK (REGEXP_LIKE(horario_embarque, '^([01][0-9]|2[0-3]):[0-5][0-9]$'));
ALTER TABLE ROTINA ADD CONSTRAINT ROTINA_DIAS_CK
    CHECK (REGEXP_LIKE(dias_semana, '^[1-7](,[1-7])*$'));

CREATE TABLE AVISO (
    id_aviso               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    id_rotina              NUMBER        NOT NULL,
    data_aviso             DATE          NOT NULL,
    letreiro               VARCHAR2(20)  NOT NULL,
    nome_ponto             VARCHAR2(160) NOT NULL,
    identificador_veiculo  VARCHAR2(20),
    minutos                NUMBER(5),
    idade_gps_segundos     NUMBER(6),
    texto                  VARCHAR2(400) NOT NULL,
    status                 VARCHAR2(15)  NOT NULL
);

ALTER TABLE AVISO ADD CONSTRAINT AVISO_PK PRIMARY KEY (id_aviso);
ALTER TABLE AVISO ADD CONSTRAINT AVISO_STATUS_CK
    CHECK (status IN ('ENVIADO', 'ATUALIZADO', 'ENCERRADO', 'SEM_PREVISAO'));
ALTER TABLE AVISO ADD CONSTRAINT AVISO_GPS_CK
    CHECK (idade_gps_segundos IS NULL OR idade_gps_segundos >= 0);
ALTER TABLE AVISO ADD CONSTRAINT AVISO_CONTEUDO_CK CHECK (
    (status = 'SEM_PREVISAO'
        AND identificador_veiculo IS NULL
        AND minutos IS NULL)
    OR
    (status IN ('ENVIADO', 'ATUALIZADO', 'ENCERRADO')
        AND identificador_veiculo IS NOT NULL
        AND minutos IS NOT NULL
        AND minutos >= 0)
);

ALTER TABLE ROTINA ADD CONSTRAINT FK_ROTINA_USUARIO
    FOREIGN KEY (id_usuario) REFERENCES USUARIO (id_usuario);
ALTER TABLE AVISO ADD CONSTRAINT FK_AVISO_ROTINA
    FOREIGN KEY (id_rotina) REFERENCES ROTINA (id_rotina);

CREATE INDEX ix_rotina_usuario ON ROTINA (id_usuario, ativa);
CREATE UNIQUE INDEX uk_aviso_rotina_dia ON AVISO (id_rotina, data_aviso);
CREATE INDEX ix_aviso_status ON AVISO (status);

