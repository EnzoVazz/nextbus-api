--   ROTINA   embarque recorrente. Ida e volta sao duas linhas.
--   AVISO    no maximo um por rotina e por dia.
--
-- Dia da semana: 1 segunda ... 7 domingo.
-- Sentido: 1 ida, 2 volta.
-- Papel: CIDADAO ou GESTOR.
-- Status do aviso: ENVIADO, ATUALIZADO, ENCERRADO, SEM_PREVISAO.
--
-- A identity comeca em 100. A carga grava os ids 1..9 na mao. O insert
-- da API, sem id, nasce em 100.
--
