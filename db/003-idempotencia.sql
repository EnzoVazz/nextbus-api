BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE IDEMPOTENCIA (
        id_idempotencia NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_usuario      NUMBER NOT NULL,
        chave           VARCHAR2(80 CHAR) NOT NULL,
        hash_corpo      VARCHAR2(128 CHAR) NOT NULL,
        id_rotina       NUMBER NOT NULL,
        CONSTRAINT IDEMPOTENCIA_CHAVE_UK UNIQUE (id_usuario, chave)
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
