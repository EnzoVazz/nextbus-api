-- ==============================================================================
-- NEXTBUS - tabela da chave de idempotencia do POST /rotinas
--
-- A API tambem cria esta tabela ao subir, se ela ainda nao existir.
-- Rode com F5 no SQL Developer somente se a subida avisar que a tabela falta.
-- Nao altera USUARIO, ROTINA nem AVISO.
-- ==============================================================================

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE IDEMPOTENCIA (
        id_idempotencia NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_usuario      NUMBER NOT NULL,
        chave           VARCHAR2(80 CHAR) NOT NULL,
        hash_corpo      VARCHAR2(128 CHAR) NOT NULL,
        id_rotina       NUMBER NOT NULL,
        CONSTRAINT IDEMPOTENCIA_CHAVE_UK UNIQUE (id_usuario, chave)
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/
